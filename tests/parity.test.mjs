import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { esm, cjs, validSecret } from './helpers.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const exportNames = [
  'CODE', 'EnvCageError', 'SecretString', 't', 'defineEnv', 'redact',
  'redactString', 'redactObject', 'safeSnapshot', 'parseDotEnv', 'loadEnvFile'
];

test('ESM and CJS expose the same top-level API names', () => {
  for (const name of exportNames) {
    assert.ok(esm[name], 'missing ESM export ' + name);
    assert.ok(cjs[name], 'missing CJS export ' + name);
    assert.equal(typeof esm[name], typeof cjs[name], name);
  }
});

test('ESM default export matches named exports', () => {
  for (const name of exportNames) {
    assert.equal(esm.default[name], esm[name], name);
  }
});

test('CJS default export is the module object', () => {
  assert.equal(cjs.default, cjs);
  for (const name of exportNames) assert.equal(cjs.default[name], cjs[name], name);
});

test('ESM and CJS error codes are identical', () => {
  assert.deepEqual({ ...cjs.CODE }, { ...esm.CODE });
});

test('ESM and CJS parse primitive values identically', () => {
  const source = {
    A: 'text',
    B: 'true',
    I: '42',
    N: '2.5',
    P: '8080',
    D: '2s',
    C: 'a,b'
  };
  const schemaEsm = {
    A: esm.t.str(), B: esm.t.bool(), I: esm.t.int(), N: esm.t.num(),
    P: esm.t.port(), D: esm.t.durationMs(), C: esm.t.csv()
  };
  const schemaCjs = {
    A: cjs.t.str(), B: cjs.t.bool(), I: cjs.t.int(), N: cjs.t.num(),
    P: cjs.t.port(), D: cjs.t.durationMs(), C: cjs.t.csv()
  };
  const left = esm.defineEnv(schemaEsm, source);
  const right = cjs.defineEnv(schemaCjs, source);
  assert.deepEqual({ ...left }, { ...right });
});

test('ESM and CJS normalize URLs identically', () => {
  const left = esm.defineEnv({ U: esm.t.url() }, { U: 'https://EXAMPLE.com' }).U;
  const right = cjs.defineEnv({ U: cjs.t.url() }, { U: 'https://EXAMPLE.com' }).U;
  assert.equal(left, right);
  assert.equal(left, 'https://example.com/');
});

test('ESM and CJS reject invalid booleans with the same issue shape', () => {
  const errors = [];
  for (const module of [esm, cjs]) {
    try {
      module.defineEnv({ B: module.t.bool() }, { B: 'maybe' });
    } catch (error) {
      errors.push(error);
    }
  }
  assert.equal(errors.length, 2);
  assert.equal(errors[0].code, errors[1].code);
  assert.deepEqual(errors[0].issues, errors[1].issues);
});

test('ESM and CJS parse dotenv input identically', () => {
  const input = 'A=1\nB="two\nthree"\n';
  const left = esm.parseDotEnv(input);
  const right = cjs.parseDotEnv(input);
  assert.deepEqual({ ...left }, { ...right });
});

test('ESM config can be redacted through CJS', () => {
  const secret = validSecret('cross-esm');
  const config = esm.defineEnv({ TOKEN: esm.t.secret() }, { TOKEN: secret });
  assert.equal(cjs.redact(config, secret), '[REDACTED]');
  assert.equal(cjs.safeSnapshot(config).TOKEN, '[REDACTED]');
});

test('CJS config can be redacted through ESM', () => {
  const secret = validSecret('cross-cjs');
  const config = cjs.defineEnv({ TOKEN: cjs.t.secret() }, { TOKEN: secret });
  assert.equal(esm.redact(config, secret), '[REDACTED]');
  assert.equal(esm.safeSnapshot(config).TOKEN, '[REDACTED]');
});

test('ESM validators can be used with CJS defineEnv', () => {
  const config = cjs.defineEnv({ PORT: esm.t.port() }, { PORT: '8080' });
  assert.equal(config.PORT, 8080);
});

test('CJS validators can be used with ESM defineEnv', () => {
  const config = esm.defineEnv({ PORT: cjs.t.port() }, { PORT: '8080' });
  assert.equal(config.PORT, 8080);
});

test('both module formats produce frozen null-prototype configs', () => {
  for (const module of [esm, cjs]) {
    const config = module.defineEnv({ A: module.t.str() }, { A: 'x' });
    assert.equal(Object.getPrototypeOf(config), null);
    assert.equal(Object.isFrozen(config), true);
  }
});

test('both module formats mask SecretString JSON output', () => {
  for (const module of [esm, cjs]) {
    const config = module.defineEnv({ S: module.t.secret() }, { S: validSecret() });
    assert.equal(JSON.stringify(config), '{"S":"[REDACTED]"}');
  }
});

test('generated CJS file has the deterministic build header', () => {
  const output = fs.readFileSync(path.join(root, 'cjs', 'index.cjs'), 'utf8');
  assert.match(output, /Generated by scripts\/build-cjs\.mjs/);
  assert.match(output, /module\.exports\.default = module\.exports/);
});

test('source of truth does not contain CommonJS require for node:fs', () => {
  const source = fs.readFileSync(path.join(root, 'src', 'index.mjs'), 'utf8');
  assert.match(source, /import \{ openSync, readSync, closeSync, fstatSync, constants as fsConstants \} from 'node:fs';/);
  assert.equal(source.includes("require('node:fs')"), false);
});

test('generated CJS does not contain ESM export declarations', () => {
  const output = fs.readFileSync(path.join(root, 'cjs', 'index.cjs'), 'utf8');
  assert.equal(/^export\s/m.test(output), false);
  assert.match(output, /const \{ openSync, readSync, closeSync, fstatSync, constants: fsConstants \} = require\('node:fs'\);/);
});

test('TypeScript declarations expose every public function', () => {
  const types = fs.readFileSync(path.join(root, 'types', 'index.d.ts'), 'utf8');
  for (const name of [
    'EnvCageError', 'SecretString', 'defineEnv', 'redact', 'redactString',
    'redactObject', 'safeSnapshot', 'parseDotEnv', 'loadEnvFile'
  ]) {
    assert.ok(types.includes(name), name);
  }
  for (const factory of [
    'str', 'secret', 'bool', 'int', 'num', 'port', 'url', 'enum', 'json', 'csv', 'durationMs'
  ]) {
    assert.ok(types.includes(factory + '(') || types.includes(factory + '<'), factory);
  }
});

test('TypeScript declarations document strict validator option surfaces', () => {
  const types = fs.readFileSync(path.join(root, 'types', 'index.d.ts'), 'utf8');
  for (const name of [
    'DefineEnvOptions', 'StringValidatorOptions', 'SecretValidatorOptions',
    'IntegerValidatorOptions', 'NumberValidatorOptions', 'UrlValidatorOptions',
    'EnumValidatorOptions', 'JsonValidatorOptions', 'CsvValidatorOptions',
    'DurationValidatorOptions', 'ParseDotEnvOptions', 'LoadEnvFileOptions'
  ]) {
    assert.ok(types.includes('interface ' + name), name);
  }
});

